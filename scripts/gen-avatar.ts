/**
 * Embed assets/github_pic.png into src/ui/avatar-data.ts so the bundled CLI
 * can display it without shipping or locating a separate asset file.
 * Usage: bun run gen:avatar
 */
import { imageInfo } from "@opentui/core";

const src = new URL("../assets/github_pic.png", import.meta.url).pathname;
const out = new URL("../src/ui/avatar-data.ts", import.meta.url).pathname;

const bytes = new Uint8Array(await Bun.file(src).arrayBuffer());
const info = imageInfo(bytes); // validates the image and reads its size
const b64 = Buffer.from(bytes).toString("base64");

await Bun.write(
  out,
  `// Generated by scripts/gen-avatar.ts from assets/github_pic.png — do not edit.\n` +
    `export const AVATAR_PX = { width: ${info.width}, height: ${info.height} };\n` +
    `export const AVATAR_PNG: Uint8Array = Uint8Array.from(Buffer.from(\n  "${b64}",\n  "base64",\n));\n`,
);
console.log(`wrote ${out} (${info.width}x${info.height}, ${bytes.length} bytes)`);
